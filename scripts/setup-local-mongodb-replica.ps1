# Setup MongoDB Community Server for Replica Set (Transaction Support)
# This script configures local MongoDB installation for better-auth transactions

Write-Host "`n=== MongoDB Replica Set Setup for Windows ===" -ForegroundColor Cyan
Write-Host "This will configure your MongoDB Community Server to support transactions`n" -ForegroundColor Yellow

# Check if running as Administrator
$isAdmin = ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
    Write-Host "ERROR: This script requires Administrator privileges" -ForegroundColor Red
    Write-Host "Right-click PowerShell and select 'Run as Administrator'" -ForegroundColor Yellow
    exit 1
}

# Detect MongoDB installation path
$mongoPath = $null
$possiblePaths = @(
    "C:\Program Files\MongoDB\Server\8.0\bin",
    "C:\Program Files\MongoDB\Server\7.0\bin",
    "C:\Program Files\MongoDB\Server\6.0\bin",
    "C:\Program Files\MongoDB\Server\5.0\bin",
    "C:\MongoDB\bin"
)

foreach ($path in $possiblePaths) {
    if (Test-Path "$path\mongod.exe") {
        $mongoPath = $path
        break
    }
}

if (-not $mongoPath) {
    Write-Host "ERROR: MongoDB installation not found" -ForegroundColor Red
    Write-Host "Searched in:" -ForegroundColor Yellow
    $possiblePaths | ForEach-Object { Write-Host "  $_" -ForegroundColor Gray }
    Write-Host "`nPlease install MongoDB Community Server from:" -ForegroundColor Yellow
    Write-Host "  https://www.mongodb.com/try/download/community" -ForegroundColor Cyan
    exit 1
}

Write-Host "✓ Found MongoDB at: $mongoPath" -ForegroundColor Green

# Detect MongoDB data directory
$dataPath = $null
$possibleDataPaths = @(
    "C:\Program Files\MongoDB\Server\8.0\data",
    "C:\Program Files\MongoDB\Server\7.0\data",
    "C:\Program Files\MongoDB\Server\6.0\data",
    "C:\Program Files\MongoDB\Server\5.0\data",
    "C:\data\db",
    "C:\MongoDB\data\db"
)

foreach ($path in $possibleDataPaths) {
    if (Test-Path $path) {
        $dataPath = $path
        break
    }
}

if (-not $dataPath) {
    # Create default data directory
    $dataPath = "C:\data\db"
    Write-Host "Creating data directory: $dataPath" -ForegroundColor Yellow
    New-Item -ItemType Directory -Path $dataPath -Force | Out-Null
}

Write-Host "✓ Data directory: $dataPath" -ForegroundColor Green

# Detect MongoDB config file
$configPath = $null
$possibleConfigPaths = @(
    "C:\Program Files\MongoDB\Server\8.0\bin\mongod.cfg",
    "C:\Program Files\MongoDB\Server\7.0\bin\mongod.cfg",
    "C:\Program Files\MongoDB\Server\6.0\bin\mongod.cfg",
    "C:\Program Files\MongoDB\Server\5.0\bin\mongod.cfg",
    "$mongoPath\mongod.cfg"
)

foreach ($path in $possibleConfigPaths) {
    if (Test-Path $path) {
        $configPath = $path
        break
    }
}

if (-not $configPath) {
    Write-Host "WARNING: MongoDB config file not found, will use default location" -ForegroundColor Yellow
    $configPath = "$mongoPath\mongod.cfg"
}

Write-Host "✓ Config file: $configPath" -ForegroundColor Green

# Backup existing config
if (Test-Path $configPath) {
    $backupPath = "$configPath.backup-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
    Write-Host "`nBacking up existing config to:" -ForegroundColor Yellow
    Write-Host "  $backupPath" -ForegroundColor Gray
    Copy-Item $configPath $backupPath
}

# Create new config with replica set enabled
Write-Host "`nCreating new MongoDB configuration with replica set..." -ForegroundColor Yellow

$configContent = @"
# MongoDB configuration file for replica set (transaction support)
# Generated by setup-local-mongodb-replica.ps1

systemLog:
  destination: file
  path: $($dataPath -replace '\\data$', '\\log')\mongod.log
  logAppend: true

storage:
  dbPath: $dataPath
  journal:
    enabled: true

net:
  port: 27017
  bindIp: 127.0.0.1,localhost

# Replica Set Configuration (REQUIRED for transactions)
replication:
  replSetName: rs0

# Optional: Enable security after initial setup
# security:
#   authorization: enabled
"@

Set-Content -Path $configPath -Value $configContent -Force
Write-Host "✓ Created replica set configuration" -ForegroundColor Green

# Stop MongoDB service if running
Write-Host "`nStopping MongoDB service..." -ForegroundColor Yellow
$mongoService = Get-Service -Name "MongoDB" -ErrorAction SilentlyContinue

if ($mongoService) {
    if ($mongoService.Status -eq "Running") {
        Stop-Service -Name "MongoDB" -Force
        Start-Sleep -Seconds 2
        Write-Host "✓ Stopped MongoDB service" -ForegroundColor Green
    }
} else {
    Write-Host "MongoDB service not found, will start manually" -ForegroundColor Yellow
}

# Create log directory if it doesn't exist
$logPath = $dataPath -replace '\\data$', '\log'
if (-not (Test-Path $logPath)) {
    New-Item -ItemType Directory -Path $logPath -Force | Out-Null
}

# Start MongoDB with replica set config
Write-Host "`nStarting MongoDB with replica set configuration..." -ForegroundColor Yellow

if ($mongoService) {
    # Start as Windows service
    Start-Service -Name "MongoDB"
    Start-Sleep -Seconds 3
    
    $mongoService = Get-Service -Name "MongoDB"
    if ($mongoService.Status -ne "Running") {
        Write-Host "ERROR: Failed to start MongoDB service" -ForegroundColor Red
        Write-Host "Try running manually:" -ForegroundColor Yellow
        Write-Host "  net start MongoDB" -ForegroundColor Gray
        exit 1
    }
} else {
    # Start manually (for portable installations)
    Write-Host "Starting MongoDB manually (no service found)..." -ForegroundColor Yellow
    $mongoProcess = Start-Process -FilePath "$mongoPath\mongod.exe" -ArgumentList "--config `"$configPath`"" -PassThru -WindowStyle Hidden
    Start-Sleep -Seconds 3
    
    if (-not $mongoProcess -or $mongoProcess.HasExited) {
        Write-Host "ERROR: Failed to start MongoDB" -ForegroundColor Red
        exit 1
    }
}

Write-Host "✓ MongoDB started" -ForegroundColor Green

# Wait for MongoDB to be ready
Write-Host "`nWaiting for MongoDB to be ready..." -ForegroundColor Yellow
$maxRetries = 10
$retryCount = 0
$mongoReady = $false

while ($retryCount -lt $maxRetries -and -not $mongoReady) {
    try {
        & "$mongoPath\mongosh.exe" --quiet --eval "db.adminCommand({ ping: 1 })" 2>&1 | Out-Null
        if ($LASTEXITCODE -eq 0) {
            $mongoReady = $true
        }
    } catch {
        # Ignore errors, keep retrying
    }
    
    if (-not $mongoReady) {
        Start-Sleep -Seconds 1
        $retryCount++
        Write-Host "." -NoNewline -ForegroundColor Gray
    }
}

if (-not $mongoReady) {
    Write-Host "`nERROR: MongoDB did not start in time" -ForegroundColor Red
    exit 1
}

Write-Host "`n✓ MongoDB is ready" -ForegroundColor Green

# Initialize replica set
Write-Host "`nInitializing replica set 'rs0'..." -ForegroundColor Yellow

$initScript = @"
try {
  const result = rs.initiate({
    _id: 'rs0',
    members: [
      { _id: 0, host: 'localhost:27017' }
    ]
  });
  
  if (result.ok === 1) {
    print('SUCCESS: Replica set initialized');
  } else {
    print('ERROR: ' + JSON.stringify(result));
  }
} catch (e) {
  if (e.message.includes('already initialized')) {
    print('INFO: Replica set already initialized');
  } else {
    print('ERROR: ' + e.message);
    throw e;
  }
}
"@

$initResult = & "$mongoPath\mongosh.exe" --quiet --eval $initScript 2>&1

if ($initResult -match "SUCCESS|already initialized") {
    Write-Host "✓ Replica set initialized successfully" -ForegroundColor Green
} else {
    Write-Host "ERROR: Failed to initialize replica set" -ForegroundColor Red
    Write-Host $initResult -ForegroundColor Gray
    exit 1
}

# Wait for replica set to elect primary
Write-Host "`nWaiting for primary election..." -ForegroundColor Yellow
Start-Sleep -Seconds 5

# Verify replica set status
Write-Host "`nVerifying replica set status..." -ForegroundColor Yellow
$statusScript = @"
const status = rs.status();
if (status.ok === 1) {
  const primary = status.members.find(m => m.stateStr === 'PRIMARY');
  if (primary) {
    print('✓ Replica set is healthy');
    print('  Primary: ' + primary.name);
    print('  State: ' + primary.stateStr);
  } else {
    print('⚠ Waiting for primary election...');
  }
} else {
  print('ERROR: ' + JSON.stringify(status));
}
"@

& "$mongoPath\mongosh.exe" --quiet --eval $statusScript

# Update .env file with replica set connection string
Write-Host "`n`n=== Configuration Complete ===" -ForegroundColor Green

$envPath = "apps\api\.env"
if (Test-Path $envPath) {
    Write-Host "`nUpdating $envPath with replica set connection string..." -ForegroundColor Yellow
    
    $envContent = Get-Content $envPath -Raw
    $newUri = "MONGODB_URI=mongodb://localhost:27017/?replicaSet=rs0"
    
    if ($envContent -match "MONGODB_URI=") {
        $envContent = $envContent -replace "MONGODB_URI=.*", $newUri
    } else {
        $envContent += "`n$newUri`n"
    }
    
    Set-Content -Path $envPath -Value $envContent.TrimEnd()
    Write-Host "✓ Updated connection string in .env" -ForegroundColor Green
}

Write-Host "`n✓ MongoDB Replica Set Setup Complete!" -ForegroundColor Green
Write-Host "`nConnection String:" -ForegroundColor Cyan
Write-Host "  mongodb://localhost:27017/?replicaSet=rs0" -ForegroundColor White

Write-Host "`nNow enable transactions in auth.service.ts:" -ForegroundColor Cyan
Write-Host "  // Uncomment this line:" -ForegroundColor Gray
Write-Host "  experimental: { joins: true }," -ForegroundColor Yellow

Write-Host "`n`nVerify replica set status anytime with:" -ForegroundColor Cyan
Write-Host "  mongosh --eval `"rs.status()`"" -ForegroundColor Gray

Write-Host "`nTo revert to standalone mode:" -ForegroundColor Yellow
Write-Host "  1. Stop MongoDB service" -ForegroundColor Gray
Write-Host "  2. Restore config from: $backupPath" -ForegroundColor Gray
Write-Host "  3. Start MongoDB service" -ForegroundColor Gray
Write-Host ""
