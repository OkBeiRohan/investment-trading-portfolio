use chrono::{DateTime, Datelike, Timelike, Utc};
use napi::bindgen_prelude::*;
use napi_derive::napi;
use serde::{Deserialize, Serialize};
use thiserror::Error;

pub mod features;
pub mod types;

pub use features::*;
pub use types::*;

#[derive(Error, Debug)]
pub enum ComputeError {
    #[error("Insufficient data: need at least {required} points, got {actual}")]
    InsufficientData { required: usize, actual: usize },

    #[error("Invalid parameter: {0}")]
    InvalidParameter(String),

    #[error("Computation failed: {0}")]
    ComputationFailed(String),
}

pub type Result<T> = std::result::Result<T, ComputeError>;

// ============================================================================
// NAPI-RS Bindings (Matches @repo/schema TypeScript types)
// ============================================================================

/// Main NAPI function: Compute features from market data
/// 
/// Input/Output types match @repo/schema MarketDataPoint and FeatureVector
/// TypeScript types are auto-generated by NAPI-RS
#[napi]
pub fn compute_features(data: Vec<MarketDataPoint>) -> napi::Result<Vec<FeatureVector>> {
    // Compute features
    let features = features::compute_features(&data)
        .map_err(|e| napi::Error::from_reason(format!("Feature computation failed: {}", e)))?;

    Ok(features)
}
