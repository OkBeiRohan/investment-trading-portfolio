pub mod features;
pub mod types;

pub use features::*;
pub use types::*;

#[derive(Error, Debug)]
pub enum ComputeError {
    #[error("Insufficient data: need at least {required} points, got {actual}")]
    InsufficientData { required: usize, actual: usize },

    #[error("Invalid parameter: {0}")]
    InvalidParameter(String),

    #[error("Computation failed: {0}")]
    ComputationFailed(String),
}

pub type Result<T> = std::result::Result<T, ComputeError>;

// ============================================================================
// NAPI-RS Bindings (Type-Safe Node.js API)
// ============================================================================

/// NAPI wrapper for MarketDataPoint (auto-generates TypeScript types)
#[napi(object)]
#[derive(Debug, Clone)]
pub struct JsMarketDataPoint {
    pub timestamp: String, // ISO 8601 string
    pub last_price: f64,
    pub volume: f64,
    pub open_interest: Option<f64>,
    pub open: Option<f64>,
    pub high: Option<f64>,
    pub low: Option<f64>,
    pub close: Option<f64>,
    pub bid_price: Option<f64>,
    pub ask_price: Option<f64>,
    pub bid_quantity: Option<f64>,
    pub ask_quantity: Option<f64>,
    pub delta: Option<f64>,
    pub gamma: Option<f64>,
    pub vega: Option<f64>,
    pub theta: Option<f64>,
    pub implied_volatility: Option<f64>,
}

/// NAPI wrapper for FeatureVector (auto-generates TypeScript types)
#[napi(object)]
