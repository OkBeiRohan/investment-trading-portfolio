/**
 * Convert an HF dataset symbol to the NSE trading symbol used in this project.
 * Falls through to the original symbol if no mapping exists.
 */
export function hfSymbolToNse(hfSymbol: string): string {
  return HF_TO_NSE_SYMBOL[hfSymbol] ?? hfSymbol;
}

/**
 * Convert an HF dataset symbol to an Upstox instrument key.
 * Returns undefined for unknown symbols.
 */
export function hfSymbolToInstrumentKey(
  hfSymbol: string,
): string | undefined {
  return HF_SYMBOL_TO_INSTRUMENT_KEY[hfSymbol];
}
